import { readdir, readFile, mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { format, resolveConfig } from 'prettier';

const root = process.cwd();
const sourceDirectory = path.join(root, 'src/content/funnels');
const outputFile = path.join(root, 'functions/_generated/funnels.ts');
const slugPattern = /^[a-z][a-z0-9]*(?:-[a-z0-9]+)*$/;

const files = (await readdir(sourceDirectory)).filter((file) => file.endsWith('.json')).sort();
const funnels = [];
const offerSlugs = new Set();
const productKeys = new Set();
const upsellKeys = new Set();

for (const file of files) {
  const value = JSON.parse(await readFile(path.join(sourceDirectory, file), 'utf8'));
  if (!slugPattern.test(value.offerSlug ?? '')) {
    throw new Error(`${file}: offerSlug must be a lowercase URL-safe name.`);
  }
  if (offerSlugs.has(value.offerSlug)) throw new Error(`${file}: duplicate offerSlug.`);
  if (!value.base?.productKey || !value.base?.name) {
    throw new Error(`${file}: base productKey and name are required.`);
  }
  if (!Array.isArray(value.upsells) || value.upsells.length > 2) {
    throw new Error(`${file}: upsells must be an array with no more than two items.`);
  }

  const products = [value.base, ...(value.bump ? [value.bump] : []), ...value.upsells];
  for (const product of products) {
    if (!slugPattern.test(product.productKey ?? '')) {
      throw new Error(`${file}: every productKey must be a lowercase URL-safe name.`);
    }
    if (productKeys.has(product.productKey)) {
      throw new Error(`${file}: duplicate productKey ${product.productKey}.`);
    }
    productKeys.add(product.productKey);
  }

  value.upsells.forEach((step, index) => {
    if (!slugPattern.test(step.key ?? '')) throw new Error(`${file}: invalid upsell key.`);
    if (upsellKeys.has(step.key)) {
      throw new Error(`${file}: upsell key ${step.key} is already used by another funnel.`);
    }
    upsellKeys.add(step.key);
    step.ordinal = index;
  });

  offerSlugs.add(value.offerSlug);
  funnels.push(value);
}

const source =
  `// Generated by scripts/generate-funnel-catalog.mjs. Do not edit by hand.\n` +
  `export const FUNNELS = ${JSON.stringify(funnels, null, 2)} as const;\n\n` +
  `export type FunnelDefinition = (typeof FUNNELS)[number];\n` +
  `export type FunnelUpsell = FunnelDefinition['upsells'][number];\n\n` +
  `export function getFunnelDefinition(offerSlug: string): FunnelDefinition | undefined {\n` +
  `  return FUNNELS.find((funnel) => funnel.offerSlug === offerSlug);\n` +
  `}\n\n` +
  `export function getProductDefinition(productKey: string) {\n` +
  `  for (const funnel of FUNNELS) {\n` +
  `    if (funnel.base.productKey === productKey) return { funnel, product: funnel.base };\n` +
  `    if (funnel.bump?.productKey === productKey) return { funnel, product: funnel.bump };\n` +
  `    const upsell = funnel.upsells.find((step) => step.productKey === productKey);\n` +
  `    if (upsell) return { funnel, product: upsell };\n` +
  `  }\n` +
  `  return undefined;\n` +
  `}\n`;

await mkdir(path.dirname(outputFile), { recursive: true });
const prettierConfig = (await resolveConfig(outputFile)) ?? {};
await writeFile(outputFile, await format(source, { ...prettierConfig, filepath: outputFile }));
console.log(`Generated ${path.relative(root, outputFile)} from ${funnels.length} funnel(s).`);
